-- Strata are stacked top-down with GROUP_CONCAT used as a window function.
-- The window's ORDER BY guarantees the order; an ORDER BY inside a subquery does not
-- (SQLite may ignore it), which could list strata out of depth order.
-- ROW_NUMBER keeps one row per hole (rn = 1), which carries the full stacked list.
WITH Strata AS (
    SELECT 
        "LOCA_ID",
        GROUP_CONCAT(
            '[' || CAST("GEOL_TOP" AS NUMERIC) || 'm - ' || "GEOL_BASE" || 'm] ' || 
            SUBSTR("GEOL_DESC", 1, 500), 
            '|'
        ) OVER (
            PARTITION BY "LOCA_ID" 
            ORDER BY CAST("GEOL_TOP" AS NUMERIC) 
            ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
        ) AS "Geology Lines",
        ROW_NUMBER() OVER (PARTITION BY "LOCA_ID" ORDER BY CAST("GEOL_TOP" AS NUMERIC)) AS rn
    FROM 
        "GEOL"
)

SELECT 
    L.geom, -- Select the spatial geometry data.
    L."LOCA_ID", -- Select the location ID.
    
    -- 1. HEADER LINE: "Borehole ID (GL: XX.XXmAOD)"
    L."LOCA_ID" || 
    CASE 
        WHEN L."LOCA_GL" IS NOT NULL AND L."LOCA_GL" != '' 
        THEN ' (GL: ' || L."LOCA_GL" || 'mAOD)' 
        ELSE '' 
    END || '|' ||
    
    -- 2. GEOLOGY LINES: The stacked, depth-ordered, truncated stratigraphy layers
    S."Geology Lines" || '|' || -- Pipe at the end drops us down to the footer line
    
    -- 3. FOOTER LINE: "Borehole ID; End of Hole: XX.XXm / XX.XXmAOD"
    L."LOCA_ID" || '; End of Hole: ' || 
    CASE 
        -- FIXED: Used L."LOCA_FDEP" consistently throughout the calculation
        WHEN L."LOCA_GL" IS NOT NULL AND L."LOCA_GL" != '' AND L."LOCA_FDEP" IS NOT NULL AND L."LOCA_FDEP" != ''
        THEN L."LOCA_FDEP" || 'm depth (' || PRINTF('%.2f', CAST(L."LOCA_GL" AS FLOAT) - CAST(L."LOCA_FDEP" AS FLOAT)) || 'mAOD)'
        
        -- Situation B: We only have Final Depth -> Just show the depth
        WHEN L."LOCA_FDEP" IS NOT NULL AND L."LOCA_FDEP" != ''
        THEN L."LOCA_FDEP" || 'm depth'
        
        -- Situation C: Data is missing
        ELSE 'Depth Unknown'
    END AS "descriptions"

FROM 
    LOCA L -- Main location table

-- Join with the stacked geology (one row per hole)
JOIN 
    Strata S
ON L."LOCA_ID" = S."LOCA_ID" AND S.rn = 1;
