-- TRIT_REM is an optional AGS heading and is often missing from real files.
-- Defaults supplies a blank value. The subquery reads TRIT_REM from TRIT when the
-- heading exists; when it doesn't, SQLite falls back to Defaults, so the query runs
-- either way instead of failing with "no such column".
WITH Defaults AS (
    SELECT '' AS TRIT_REM
)

SELECT 
    -- 1. QGIS Unique Feature Identifier
    ROW_NUMBER() OVER () AS fid,

    -- 2. Location & Spatial Identifiers
    T.LOCA_ID AS "Exploratory Hole Location",
-- STREAMING_CHUNK: Mapping National Grid coordinate fields...
    CAST(NULLIF(L.LOCA_NATE, '') AS REAL) AS "Easting",
    CAST(NULLIF(L.LOCA_NATN, '') AS REAL) AS "Northing",
    CAST(NULLIF(L.LOCA_GL, '') AS REAL) AS "Ground Level (mAOD)",
    
    -- 3. Specimen Specifics & Sample Metadata
    T.SAMP_REF AS "Sample Reference",
    T.SAMP_TYPE AS "Sample Type",
    CAST(NULLIF(T.SAMP_TOP, '') AS REAL) AS "Sample top depth",
    T.SPEC_REF AS "Specimen Reference",
    
-- STREAMING_CHUNK: Executing depth-matched geological legend lookup...
    -- Dynamic Geology Legend Code lookup at specimen depth (from GEOL_LEG)
    (
        SELECT G.GEOL_LEG 
        FROM GEOL G 
        WHERE G.LOCA_ID = T.LOCA_ID 
          AND CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL) >= CAST(NULLIF(G.GEOL_TOP, '') AS REAL)
          AND CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL) <= CAST(NULLIF(G.GEOL_BASE, '') AS REAL)
        -- Boundary rule (B1): a depth on a boundary matches both strata; DESC picks the lower
        -- one, i.e. the stratum that starts at that depth (the test is in the ground below it).
        -- At the base of the hole only the last stratum matches, so it is still found.
        ORDER BY CAST(NULLIF(G.GEOL_TOP, '') AS REAL) DESC 
        LIMIT 1
    ) AS "Geology Legend Code (GEOL_LEG)",
    
    -- 4. Depth & Calculated Specimen Levels
    -- Prioritises SPEC_DPTH (specimen-specific depth) and falls back to SAMP_TOP
    CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL) AS "Specimen Depth (m)",
    
    -- Level calculation: Z = Ground Level - Specimen Depth
    ROUND(
        CAST(NULLIF(L.LOCA_GL, '') AS REAL) - 
        CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL), 
        2
    ) AS "Specimen Level (mAOD)",

-- STREAMING_CHUNK: Correlating specimen depth with geological unit descriptions...
    -- 5. Dynamic Geological Description lookup at specimen depth
    -- Uses a subquery with LIMIT 1 to prevent row multiplication in case of overlapping GEOL boundaries
    (
        SELECT G.GEOL_DESC 
        FROM GEOL G 
        WHERE G.LOCA_ID = T.LOCA_ID 
          AND CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL) >= CAST(NULLIF(G.GEOL_TOP, '') AS REAL)
          AND CAST(COALESCE(NULLIF(T.SPEC_DPTH, ''), NULLIF(T.SAMP_TOP, '')) AS REAL) <= CAST(NULLIF(G.GEOL_BASE, '') AS REAL)
        -- Boundary rule (B1): a depth on a boundary matches both strata; DESC picks the lower
        -- one, i.e. the stratum that starts at that depth (the test is in the ground below it).
        -- At the base of the hole only the last stratum matches, so it is still found.
        ORDER BY CAST(NULLIF(G.GEOL_TOP, '') AS REAL) DESC 
        LIMIT 1
    ) AS "Sample Geology Description",

    -- 6. Core Geotechnical Test Results
    -- Casts results to preserve numeric compatibility for thematic mapping and statistics
    CAST(NULLIF(T.TRIT_CU, '') AS REAL) AS "Undrained Shear Strength at Failure (kPa)",
    CAST(NULLIF(T.TRIT_BDEN, '') AS REAL) AS "Initial Bulk Density (Mg/m3)",
    CAST(NULLIF(T.TRIT_DDEN, '') AS REAL) AS "Initial Dry Density (Mg/m3)",
    CAST(NULLIF(T.TRIT_CELL, '') AS REAL) AS "Cell Pressure (kPa)",
    CAST(NULLIF(T.TRIT_DEVF, '') AS REAL) AS "Deviator Stress at Failure (kPa)",
    CAST(NULLIF(T.TRIT_STRN, '') AS REAL) AS "Axial Strain at Failure (%)",
    
    -- Include comments and geometry
    (SELECT TRIT_REM FROM TRIT F WHERE F.rowid = T.rowid) AS "Test Remarks",
    L.geom

FROM 
    TRIT T
    CROSS JOIN Defaults

-- Join location parameters to calculate levels and fetch coordinates
LEFT JOIN 
    loca L ON T.LOCA_ID = L.LOCA_ID

ORDER BY 
    T.LOCA_ID ASC, 
    "Specimen Depth (m)" ASC, 
    T.SPEC_REF ASC, 
    T.TRIT_TESN ASC;
