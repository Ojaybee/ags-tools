WITH MadeGroundRecords AS (
    -- Filter the GEOL table based on the assumption that codes starting with '1' represent Made Ground,
    -- except 101 (TOPSOIL), which is natural ground and must not be reported as Made Ground
    SELECT 
        G.LOCA_ID,
        CAST(NULLIF(G.GEOL_BASE, '') AS REAL) AS Cleaned_Base
    FROM 
        GEOL G
    WHERE 
        SUBSTR(G.GEOL_LEG, 1, 1) = '1'
        AND CAST(G.GEOL_LEG AS REAL) <> 101
)

SELECT 
    -- 1. QGIS Unique Feature Identifier (Mandatory for Virtual Layers and database mapping)
    ROW_NUMBER() OVER () AS fid,

    -- 2. Location & Spatial Identifiers (Robust tabular and geometric coordinate extraction)
    MG.LOCA_ID AS "Exploratory Hole Location",
    COALESCE(CAST(NULLIF(L.LOCA_NATE, '') AS REAL), X(L.geom)) AS "Easting",
    COALESCE(CAST(NULLIF(L.LOCA_NATN, '') AS REAL), Y(L.geom)) AS "Northing",
    CAST(NULLIF(L.LOCA_GL, '') AS REAL) AS "Ground Level (mAOD)",
    
    -- 3. Made Ground Bottom Depths
    MAX(MG.Cleaned_Base) AS "Depth to Base of Made Ground (m)",
    
    -- 4. Calculated Levels (Dual outputs: Text Warning for auditing, Numeric for Plotting/Contouring)
    
    -- Check if the maximum MG base equals or exceeds the total borehole depth (EOH)
    -- If the final depth (LOCA_FDEP) or the MG base depth is missing, the base cannot be confirmed
    CASE
        WHEN MAX(MG.Cleaned_Base) IS NULL OR CAST(NULLIF(L.LOCA_FDEP, '') AS REAL) IS NULL
        THEN 'Unknown; missing final depth or MG base'
        WHEN MAX(MG.Cleaned_Base) >= CAST(NULLIF(L.LOCA_FDEP, '') AS REAL)
        THEN 'MG not bottomed; > ' || L.LOCA_FDEP
        ELSE CAST(ROUND(CAST(NULLIF(L.LOCA_GL, '') AS REAL) - MAX(MG.Cleaned_Base), 2) AS TEXT)
    END AS "Base Reduced Level (m)",

    -- Clean numeric elevation column to ensure charting software and contour tools do not break on text warnings
    CASE
        WHEN MAX(MG.Cleaned_Base) IS NULL OR CAST(NULLIF(L.LOCA_FDEP, '') AS REAL) IS NULL
        THEN NULL
        WHEN MAX(MG.Cleaned_Base) >= CAST(NULLIF(L.LOCA_FDEP, '') AS REAL)
        THEN NULL
        ELSE ROUND(CAST(NULLIF(L.LOCA_GL, '') AS REAL) - MAX(MG.Cleaned_Base), 2)
    END AS "Numeric Base Level (mAOD)",

    -- 5. Status & Quality Tagging
    CASE
        WHEN MAX(MG.Cleaned_Base) IS NULL OR CAST(NULLIF(L.LOCA_FDEP, '') AS REAL) IS NULL
        THEN 'Unknown (Missing Depth Data)'
        WHEN MAX(MG.Cleaned_Base) >= CAST(NULLIF(L.LOCA_FDEP, '') AS REAL)
        THEN 'Uncertain (Not Bottomed)'
        ELSE 'Confirmed Base'
    END AS "Stratum Status",
    
    -- 6. Dynamic 3D Spatial Geometry Construction
    -- Set geom to NULL if the stratum base was not bottomed or cannot be confirmed (missing depth data),
    -- as we cannot identify the actual geometry of the boundary.
    -- Otherwise, construct a 3D point (MakePointZ) using the calculated Z base level, in the
    -- CRS of the LOCA layer (SRID of L.geom, i.e. the CRS chosen in AGS2DB).
    CASE
        WHEN MAX(MG.Cleaned_Base) IS NULL OR CAST(NULLIF(L.LOCA_FDEP, '') AS REAL) IS NULL
        THEN NULL
        WHEN MAX(MG.Cleaned_Base) >= CAST(NULLIF(L.LOCA_FDEP, '') AS REAL)
        THEN NULL
        ELSE MakePointZ(X(L.geom), Y(L.geom), ROUND(CAST(NULLIF(L.LOCA_GL, '') AS REAL) - MAX(MG.Cleaned_Base), 2), SRID(L.geom))
    END AS geom

FROM 
    MadeGroundRecords MG

-- Join with the spatial locations table to get coordinates/geometries and ground levels
JOIN 
    loca L ON MG.LOCA_ID = L.LOCA_ID

-- Group by location parameters to correctly aggregate the MAX() depth and math functions per borehole
GROUP BY 
    MG.LOCA_ID, 
    L.geom,
    L.LOCA_GL,
    L.LOCA_FDEP,
    L.LOCA_NATE,
    L.LOCA_NATN;
