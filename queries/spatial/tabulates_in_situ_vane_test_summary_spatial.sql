SELECT 
    -- 1. QGIS Unique Feature Identifier
    ROW_NUMBER() OVER () AS fid,

    -- 2. Location & Spatial Identifiers
    I.LOCA_ID AS "Exploratory Hole Location",
    CAST(NULLIF(L.LOCA_NATE, '') AS REAL) AS "Easting",
    CAST(NULLIF(L.LOCA_NATN, '') AS REAL) AS "Northing",
    CAST(NULLIF(L.LOCA_GL, '') AS REAL) AS "Ground Level (mAOD)",
    
    -- 3. Dynamic Geology Legend Lookup
    -- Pulls the legend code from GEOL_LEG at the exact depth of the test
    (
        SELECT G.GEOL_LEG 
        FROM GEOL G 
        WHERE G.LOCA_ID = I.LOCA_ID 
          AND CAST(NULLIF(I.IVAN_DPTH, '') AS REAL) >= CAST(NULLIF(G.GEOL_TOP, '') AS REAL)
          AND CAST(NULLIF(I.IVAN_DPTH, '') AS REAL) <= CAST(NULLIF(G.GEOL_BASE, '') AS REAL)
        -- Boundary rule (B1): a depth on a boundary matches both strata; DESC picks the lower
        -- one, i.e. the stratum that starts at that depth (the test is in the ground below it).
        -- At the base of the hole only the last stratum matches, so it is still found.
        ORDER BY CAST(NULLIF(G.GEOL_TOP, '') AS REAL) DESC 
        LIMIT 1
    ) AS "Geology Legend Code (GEOL_LEG)",

    -- 4. Depth & Calculated Test Levels
    CAST(NULLIF(I.IVAN_DPTH, '') AS REAL) AS "Test Depth (m)",
    
    -- Level calculation: Z = Ground Level - Test Depth
    ROUND(
        CAST(NULLIF(L.LOCA_GL, '') AS REAL) - 
        CAST(NULLIF(I.IVAN_DPTH, '') AS REAL), 
        2
    ) AS "Test Level (mAOD)",

    -- 5. Dynamic Geological Description Lookup
    -- Uses a subquery with LIMIT 1 to prevent row multiplication in case of overlapping GEOL boundaries
    (
        SELECT G.GEOL_DESC 
        FROM GEOL G 
        WHERE G.LOCA_ID = I.LOCA_ID 
          AND CAST(NULLIF(I.IVAN_DPTH, '') AS REAL) >= CAST(NULLIF(G.GEOL_TOP, '') AS REAL)
          AND CAST(NULLIF(I.IVAN_DPTH, '') AS REAL) <= CAST(NULLIF(G.GEOL_BASE, '') AS REAL)
        -- Boundary rule (B1): a depth on a boundary matches both strata; DESC picks the lower
        -- one, i.e. the stratum that starts at that depth (the test is in the ground below it).
        -- At the base of the hole only the last stratum matches, so it is still found.
        ORDER BY CAST(NULLIF(G.GEOL_TOP, '') AS REAL) DESC 
        LIMIT 1
    ) AS "Test Geology Description",

    -- 6. Core Vane Test Specifics (AGS 4 Guidelines)
    I.IVAN_TESN AS "Test Reference",
    I.IVAN_METH AS "Test Standard / Method",
    I.IVAN_TYPE AS "Vane Type",

    -- 7. Core Geotechnical Test Results
    -- Casts results to preserve numeric compatibility for thematic mapping and plotting
    CAST(NULLIF(I.IVAN_IVAN, '') AS REAL) AS "Peak Undrained Shear Strength (kPa)",
    CAST(NULLIF(I.IVAN_IVAR, '') AS REAL) AS "Remoulded Undrained Shear Strength (kPa)",
    
    -- Dynamic Sensitivity Calculation (Peak / Remoulded)
    -- Safely checks for nulls and prevents division-by-zero errors in SQLite
    CASE 
        WHEN CAST(NULLIF(I.IVAN_IVAR, '') AS REAL) > 0 
        THEN ROUND(CAST(NULLIF(I.IVAN_IVAN, '') AS REAL) / CAST(NULLIF(I.IVAN_IVAR, '') AS REAL), 2)
        ELSE NULL 
    END AS "Sensitivity (Calculated)",

    -- 8. Remarks & Environmental Geometry
    I.IVAN_REM AS "Test Remarks",
    L.geom

FROM 
    IVAN I

-- Spatial join with Location parameters
LEFT JOIN 
    loca L ON I.LOCA_ID = L.LOCA_ID

ORDER BY 
    I.LOCA_ID ASC, 
    "Test Depth (m)" ASC,
    I.IVAN_TESN ASC;
