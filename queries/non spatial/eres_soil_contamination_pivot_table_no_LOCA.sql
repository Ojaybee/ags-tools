--   horizontal matrix. Reorganizes every physical sample soil core into a single 
--   row, positioning all 122 determinand columns in the exact sequence of the 
--   soil screening sheet.
--
--   NON-SPATIAL VARIANT: This query does not join to the LOCA table. It is designed
--   to run on raw environmental data where coordinate tables are empty or missing.
--
--   Converts separate sample keys into a single concatenated "Unique Sample Identifier"
--   (using the formula: LOCA_ID_SAMP_TOP_SAMP_TYPE_SAMP_REF) to act as a robust 
--   lookup key for Excel formulas. Uses COALESCE and NULLIF to prevent the string from
--   becoming empty/null if one of the fields is empty.
--
--   Uses ERES_RTXT to preserve reporting thresholds and laboratory qualifiers 
--   (e.g., "<0.1", ">50") in the final exported grid.
--
--   Filters out liquid units (mg/l, ug/l) to guarantee only soil results are returned.
--   Handles typical lab typos (e.g., 'Napthalene') and mirrors spreadsheet-specific
--   trailing spaces in aliases to allow seamless copy-pasting.
