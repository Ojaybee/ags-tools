    -- 1. Unique Row Identifier for tracking in flat tables
    ROW_NUMBER() OVER () AS fid,

    -- 2. Concatenated Unique Sample Identifier (Excel Lookup Key)
    COALESCE(NULLIF(E.LOCA_ID, ''), '-')   || '_' || 
    COALESCE(NULLIF(E.SAMP_TOP, ''), '-')  || '_' || 
